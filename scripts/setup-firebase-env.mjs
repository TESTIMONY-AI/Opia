#!/usr/bin/env node
/**
 * Writes .env.local from Firebase web app config.
 * Run: npm run firebase:env
 * Or paste values when prompted.
 */
import { createInterface } from 'node:readline/promises';
import { writeFile, access } from 'node:fs/promises';
import { constants } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env.local');

const KEYS = [
  ['VITE_FIREBASE_API_KEY', 'apiKey'],
  ['VITE_FIREBASE_AUTH_DOMAIN', 'authDomain'],
  ['VITE_FIREBASE_PROJECT_ID', 'projectId'],
  ['VITE_FIREBASE_STORAGE_BUCKET', 'storageBucket'],
  ['VITE_FIREBASE_MESSAGING_SENDER_ID', 'messagingSenderId'],
  ['VITE_FIREBASE_APP_ID', 'appId'],
];

async function fileExists(path) {
  try {
    await access(path, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}

function parseConfigBlock(text) {
  const out = {};
  for (const [, jsKey] of KEYS) {
    const re = new RegExp(`${jsKey}\\s*:\\s*["'\`]([^"'\`]+)["'\`]`);
    const m = text.match(re);
    if (m) out[jsKey] = m[1];
  }
  return out;
}

async function main() {
  const rl = createInterface({
    input: process.stdin,
    output: process.stdout,
  });

  console.log('\nOPIA — Firebase .env.local setup\n');
  console.log(
    'Get config: Firebase Console → Project settings → Your apps → Web app → firebaseConfig\n',
  );

  if (await fileExists(envPath)) {
    const ans = await rl.question(
      '.env.local already exists. Overwrite? (y/N) ',
    );
    if (ans.trim().toLowerCase() !== 'y') {
      console.log('Cancelled.');
      rl.close();
      return;
    }
  }

  const paste = await rl.question(
    'Paste the whole firebaseConfig block (or press Enter to type each field):\n',
  );

  const values = {};
  const parsed = parseConfigBlock(paste);
  const hasParsed = KEYS.every(([, jsKey]) => parsed[jsKey]);

  if (hasParsed) {
    for (const [, jsKey] of KEYS) values[jsKey] = parsed[jsKey];
    console.log('Parsed config from paste.');
  } else {
    for (const [envKey, jsKey] of KEYS) {
      const v = await rl.question(`${envKey}: `);
      values[jsKey] = v.trim();
    }
  }

  rl.close();

  const missing = KEYS.filter(([, jsKey]) => !values[jsKey]);
  if (missing.length) {
    console.error('\nMissing:', missing.map(([k]) => k).join(', '));
    process.exit(1);
  }

  const lines = [
    '# Generated by npm run firebase:env — do not commit',
    ...KEYS.map(
      ([envKey, jsKey]) => `${envKey}=${values[jsKey]}`,
    ),
    '',
  ];

  await writeFile(envPath, lines.join('\n'), 'utf8');
  console.log(`\nWrote ${envPath}`);
  console.log('Next: npm run firebase:login && npm run firebase:deploy-rules');
  console.log('Then: npm run dev\n');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
